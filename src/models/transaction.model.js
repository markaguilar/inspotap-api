const mongoose = require('mongoose');

// ── Embedded TransactionItem schema ───────────────────────────────────────────
// Stored as a snapshot at time of sale — never rely on live product data
// for history. This protects profit calculations when prices change later.

const transactionItemSchema = new mongoose.Schema(
  {
    product: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Product',
      required: true,
    },

    // Snapshots — captured from product at time of sale
    productName: {
      type: String,
      required: true,
      trim: true,
    },
    sku: {
      type: String,
      default: '',
      trim: true,
    },
    unit: {
      type: String,
      default: 'piece',
      trim: true,
    },

    qty: {
      type: Number,
      required: true,
      min: [1, 'Quantity must be at least 1.'],
    },

    // Price snapshot at time of sale — never changes after checkout
    unitPrice: {
      type: Number,
      required: true,
      min: [0, 'Unit price must be 0 or more.'],
    },

    // Buying price snapshot — used for profit calculation in reports
    // Stored here so profit is accurate even if buying price changes later
    buyingPrice: {
      type: Number,
      required: true,
      min: [0, 'Buying price must be 0 or more.'],
      default: 0,
    },

    // qty × unitPrice — pre-computed and stored for fast aggregation
    totalPrice: {
      type: Number,
      required: true,
      min: [0, 'Total price must be 0 or more.'],
    },
  },
  {
    _id: false, // embedded, no separate _id needed
  }
);

// ── Main Transaction schema ───────────────────────────────────────────────────

const transactionSchema = new mongoose.Schema(
  {
    // Human-readable receipt number: TXN-YYYYMMDD-XXXX
    // Generated by the service using saleDate (not createdAt) so backdated
    // manual entries get the correct date prefix
    receiptNo: {
      type: String,
      unique: true,
      sparse: true, // allows null during creation before receiptNo is assigned
      trim: true,
    },

    // ── Items ──────────────────────────────────────────────────────────────
    items: {
      type: [transactionItemSchema],
      required: true,
      validate: {
        validator: (v) => Array.isArray(v) && v.length > 0,
        message: 'Transaction must have at least one item.',
      },
    },

    // ── Amounts ────────────────────────────────────────────────────────────
    subtotal: {
      type: Number,
      required: true,
      min: [0, 'Subtotal must be 0 or more.'],
      // Sum of all item.totalPrice before discount
    },

    discount: {
      type: Number,
      default: 0,
      min: [0, 'Discount must be 0 or more.'],
    },

    totalAmount: {
      type: Number,
      required: true,
      min: [0, 'Total amount must be 0 or more.'],
      // subtotal - discount
    },

    // Cash handling — optional for non-cash payments
    cashTendered: {
      type: Number,
      default: 0,
      min: [0, 'Cash tendered must be 0 or more.'],
    },

    change: {
      type: Number,
      default: 0,
      min: [0, 'Change must be 0 or more.'],
      // cashTendered - totalAmount (floored at 0)
    },

    // ── Payment ────────────────────────────────────────────────────────────
    paymentMethod: {
      type: String,
      enum: {
        values: ['cash', 'gcash', 'maya', 'utang', 'other'],
        message: 'Payment method must be one of: cash, gcash, maya, utang, other.',
      },
      default: 'cash',
    },

    // ── Source / manual entry ──────────────────────────────────────────────
    /**
     * source:
     *   'pos'           — created live on the cashier screen
     *   'manual_entry'  — backdated entry recorded by owner after the fact
     *
     * Always use saleDate for reports, never createdAt.
     * Reports filter by source to allow owner to view POS-only or all sales.
     */
    source: {
      type: String,
      enum: {
        values: ['pos', 'manual_entry'],
        message: 'Source must be either "pos" or "manual_entry".',
      },
      default: 'pos',
    },

    /**
     * saleDate — ACTUAL date/time of the sale.
     * For live POS: equals createdAt.
     * For manual entries: set by owner — can be in the past.
     * ALL reports must use this field, not createdAt.
     */
    saleDate: {
      type: Date,
      required: true,
      default: Date.now,
    },

    /**
     * soldBy — free-text name of who was at the counter.
     * Does NOT require a system account. Covers Nanay, Tatay, helpers, etc.
     * For live POS, populated from req.user.name automatically.
     */
    soldBy: {
      type: String,
      required: true,
      trim: true,
      default: 'Owner',
    },

    /**
     * cashier — link to a User account.
     * Null for manual entries where the seller has no account.
     * Populated from req.user._id on checkout.
     */
    cashier: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null,
    },

    /**
     * shift — link to the open Shift at time of checkout.
     * Null for manual entries or if shift system is not used.
     * Set automatically in transaction.service.js if a shift is open.
     */
    shift: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Shift',
      default: null,
    },

    notes: {
      type: String,
      trim: true,
      default: '',
    },

    // ── Status & void ──────────────────────────────────────────────────────
    status: {
      type: String,
      enum: {
        values: ['completed', 'voided', 'refunded'],
        message: 'Status must be one of: completed, voided, refunded.',
      },
      default: 'completed',
    },

    // Populated only when status = 'voided'
    voidedAt: {
      type: Date,
      default: null,
    },
    voidedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      default: null,
    },
    voidReason: {
      type: String,
      trim: true,
      default: '',
    },
  },
  {
    timestamps: true,
    // createdAt = when the DB record was saved
    // saleDate  = the ACTUAL time of sale — use this in all reports
  }
);

// ── Indexes ───────────────────────────────────────────────────────────────────

// Primary query pattern: filter by date range
transactionSchema.index({ saleDate: -1 });

// Filter by source (pos vs manual_entry) + date
transactionSchema.index({ source: 1, saleDate: -1 });

// Filter by cashier + date (cashier views their own history)
transactionSchema.index({ cashier: 1, saleDate: -1 });

// Filter by soldBy name (Nanay report)
transactionSchema.index({ soldBy: 1, saleDate: -1 });

// Filter by status
transactionSchema.index({ status: 1, saleDate: -1 });

// Filter by shift
transactionSchema.index({ shift: 1 });

// Receipt number lookup
transactionSchema.index({ receiptNo: 1 }, { unique: true, sparse: true });

// ── Virtuals ──────────────────────────────────────────────────────────────────

/**
 * grossProfit — total profit for this transaction.
 * (unitPrice - buyingPrice) × qty per item, summed.
 * Not stored — computed from snapshots on demand.
 */
transactionSchema.virtual('grossProfit').get(function () {
  return this.items.reduce((sum, item) => {
    return sum + (item.unitPrice - item.buyingPrice) * item.qty;
  }, 0);
});

/**
 * itemCount — total units sold (sum of all item.qty).
 */
transactionSchema.virtual('itemCount').get(function () {
  return this.items.reduce((sum, item) => sum + item.qty, 0);
});

// ── Model ─────────────────────────────────────────────────────────────────────

const Transaction = mongoose.model('Transaction', transactionSchema);

module.exports = Transaction;
